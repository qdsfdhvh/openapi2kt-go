package core_test

import (
	"encoding/json"
	"openapi-kt/core"
	"testing"
)

func TestIntrinsicNullablePrimitiveBothSpellings(t *testing.T) {
	for _, p := range []struct{ kind, format, name string }{{"string", "", "String"}, {"string", "uuid", "String"}, {"boolean", "", "Boolean"}, {"integer", "int32", "Int"}, {"integer", "int64", "Long"}, {"number", "float", "Float"}, {"number", "double", "Double"}} {
		for _, array := range []bool{false, true} {
			for _, flag := range []bool{false, true} {
				scalar := map[string]any{"type": p.kind}
				if p.format != "" {
					scalar["format"] = p.format
				}
				if array {
					scalar["type"] = []string{p.kind, "null"}
				} else {
					scalar["nullable"] = true
				}
				b, e := json.Marshal(map[string]any{"openapi": "3.1.0", "components": map[string]any{"schemas": map[string]any{"Z": scalar, "A": map[string]any{"$ref": "#/components/schemas/Z", "nullable": false}}}})
				if e != nil {
					t.Fatal(e)
				}
				req := request(b, "Dto")
				req.Options.Validation = flag
				got, e := core.GenerateWithDiagnostics(req)
				if e != nil {
					t.Fatal(e)
				}
				prefix := "// Generated by openapi-kt. Do not edit.\npackage org.example.models.models\n\npublic typealias "
				if s := source(t, got, "ZDto"); s != prefix+"ZDto = kotlin."+p.name+"?\n" {
					t.Fatal(s)
				}
				if s := source(t, got, "ADto"); s != prefix+"ADto = kotlin."+p.name+"\n" {
					t.Fatal(s)
				}
			}
		}
	}
}
func TestIntrinsicNullablePrimitiveCheckedCollections(t *testing.T) {
	for _, n := range []int{16, 17} {
		leaf := `{"$ref":"#/components/schemas/Z"}`
		for range n {
			leaf = `{"type":"array","items":` + leaf + `}`
		}
		req := request(schemas(`{"Z":{"type":["string","null"],"minLength":2},"Holder":{"properties":{"v":`+leaf+`}}}`), "Dto")
		req.Options.Validation = true
		got, e := core.GenerateWithDiagnostics(req)
		if n == 16 {
			if e != nil {
				t.Fatal(e)
			}
		} else if e == nil || e.(core.Diagnostics)[0].Code != "E_SCHEMA_DEPTH" || len(got.Artifacts.Files) != 0 || len(got.Warnings) != 0 {
			t.Fatal(got, e)
		}
	}
}
