func TestValueConstraintGuards(t *testing.T) {
	for _, tc := range []struct{ kind, extra, key, code string }{
		{"string", `"minLength":-1`, "minLength", "E_SCHEMA_INVALID"},
		{"string", `"maxLength":1.5`, "maxLength", "E_SCHEMA_INVALID"},
		{"string", `"minLength":null`, "minLength", "E_SCHEMA_INVALID"},
		{"string", `"maxLength":2147483648`, "maxLength", "E_SCHEMA_INVALID"},
		{"string", `"minLength":3,"maxLength":2`, "maxLength", "E_SCHEMA_INVALID"},
		{"string", `"minimum":0`, "minimum", "E_SCHEMA_UNSUPPORTED"},
		{"string", `"pattern":"(?<=x).*"`, "pattern", "E_SCHEMA_UNSUPPORTED"},
		{"boolean", `"minimum":0`, "minimum", "E_SCHEMA_UNSUPPORTED"},
		{"integer", `"minimum":1.5`, "minimum", "E_SCHEMA_INVALID"},
		{"integer", `"minimum":"0"`, "minimum", "E_SCHEMA_INVALID"},
		{"integer", `"maximum":2147483648`, "maximum", "E_SCHEMA_INVALID"},
		{"integer", `"format":"int64","maximum":9223372036854775808`, "maximum", "E_SCHEMA_INVALID"},
		{"integer", `"minimum":2,"maximum":1`, "maximum", "E_SCHEMA_INVALID"},
		{"number", `"maximum":1e-999999`, "maximum", "E_SCHEMA_INVALID"},
		{"number", `"format":"float","maximum":3.5e38`, "maximum", "E_SCHEMA_INVALID"},
		{"number", `"format":"float","minimum":0.1000000002,"maximum":0.1000000001`, "maximum", "E_SCHEMA_INVALID"},
		{"number", `"minLength":1`, "minLength", "E_SCHEMA_UNSUPPORTED"},
		{"number", `"maximum":1.` + strings.Repeat("0", 260), "maximum", "E_SCHEMA_INVALID"},
	} {
		input := schemas(`{"Id":{"type":"` + tc.kind + `","x-kotlin-value-class":true,` + tc.extra + `}}`)
		failure(t, input, tc.code, "/components/schemas/Id/"+tc.key)
	}
	failure(t, schemas(`{"Id":{"type":"string","x-kotlin-value-class":false,"minLength":1}}`), "E_SCHEMA_UNSUPPORTED", "/components/schemas/Id/minLength")
	failure(t, fieldDoc(`{"type":"string","minLength":1}`), "E_SCHEMA_UNSUPPORTED", "/components/schemas/Record/properties/value/minLength")
	unconstrained := source(t, report(t, schemas(`{"Id":{"type":"string","x-kotlin-value-class":true}}`), ""), "Id")
	want := "// Generated by openapi-kt. Do not edit.\npackage org.example.models.models\n\n@kotlinx.serialization.Serializable\n@kotlin.jvm.JvmInline\npublic value class Id(\n    public val rawValue: kotlin.String,\n)\n"
	if unconstrained != want {
		t.Fatal("unconstrained wrapper output changed", unconstrained)
	}
	// The baseline serializer/slot metadata does not acquire checks at use sites.
	report(t, schemas(`{"Id":{"type":"string","x-kotlin-value-class":true,"minLength":0,"maxLength":0}}`), "")
}

func TestValueClassConstraints(t *testing.T) {
	input, err := os.ReadFile(filepath.Join(testutil.RepoRoot(), "tests", "fixtures", "http", "value-constraints.json"))
	if err != nil {
		t.Fatal(err)
	}
	r := report(t, input, "Dto")
	for _, tc := range []struct{ name, token string }{{"NameDto", "rawValue.indices.count"}, {"NameDto", "require(length >= 1)"}, {"NameDto", "require(length <= 2)"}, {"CountDto", "rawValue >= -2L"}, {"CountDto", "rawValue <= 2L"}, {"EdgeDto", "rawValue >= -9223372036854775806L"}, {"RateDto", "rawValue.isFinite()"}, {"ScaleDto", "rawValue <= 0.1f"}} {
		if !strings.Contains(source(t, r, tc.name), tc.token) {
			t.Fatal(tc, source(t, r, tc.name))
		}
	}
}
