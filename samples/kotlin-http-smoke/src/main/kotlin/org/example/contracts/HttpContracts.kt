        calls++
        check(request.url.protocol.name == "https")
        check(request.url.host == "api.example.test")
        when (calls) {
            1 -> {
                check(request.method == HttpMethod.Get)
                check(request.url.encodedPath == "/v1/widgets/a%2Fb%3F%23%20%E9%9B%AA%25") { request.url.toString() }
