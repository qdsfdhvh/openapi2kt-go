            2 -> {
                check(request.url.encodedPath == "/v1/widgets/plain")
                check(request.url.parameters.isEmpty())
                check(request.headers["X-Trace-Id"] == null)
                respond("""{"id":"two"}""", HttpStatusCode.OK, headersOf("Content-Type", "application/json"))
            }
            3 -> {
                check(request.method == HttpMethod.Delete)
                check(request.url.encodedPath == "/v1/widgets/plain")
                respond("", HttpStatusCode.NoContent)
            }
            4 -> {
                check(request.url.encodedPath == "/overridden")
                // Ktor's url(String) changes the target but retains existing query parameters.
                check(request.url.parameters["state"] == "future")
                check(request.headers["X-Trace-Id"] == "last")
                respond("""{"id":"override"}""", HttpStatusCode.OK, headersOf("Content-Type", "application/json"))
            }
            5 -> {
                check(request.url.encodedPath == "/custom/health")
                respond("", HttpStatusCode.NoContent)
            }
            6 -> {
                check(request.url.encodedPath == "/v1/admin/status")
                respond("42", HttpStatusCode.OK, headersOf("Content-Type", "application/json"))
            }
            7 -> {
                check(request.method == HttpMethod.Get)
                check(request.url.encodedPath == "/v1/edge/literal/\$count") { request.url.toString() }
                check(request.url.parameters["method"] == "wire-method")
                check(request.url.parameters["basePath"] == "not-the-base")
                check(request.url.parameters["when"] == "false")
                check(request.url.parameters["requestBuilder"] == "not-the-builder")
                check(request.headers["client"] == "header-client")
                respond("", HttpStatusCode.NoContent)
            }
            8 -> {
                check(request.url.encodedPath == "/still-usable")
                respond("", HttpStatusCode.NoContent)
            }
            else -> error("Unexpected call")
        }
