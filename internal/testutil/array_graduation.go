package testutil

import (
	"strings"
	"testing"
)

// ArrayGraduation explicitly graduates the historical component schema case,
// never the invalid document-root [] case. Original fixture bytes stay intact.
func ArrayGraduation(c Case) bool { return c.ID == "array-component" }

func CheckArrayGraduation(t testing.TB, c Case, files map[string]string) {
	t.Helper()
	if c.ID != "array-component" || c.Expect.Kind != "error" || c.Expect.Code != "E_SCHEMA_UNSUPPORTED" || c.Input != "invalid/array-component.json" {
		t.Fatal("invalid historical array graduation identity", c)
	}
	path := strings.ReplaceAll(c.PackageName, ".", "/") + "/models/Record" + c.ModelNameSuffix + ".kt"
	want := "// Generated by openapi-kt. Do not edit.\npackage " + c.PackageName + ".models\n\npublic typealias Record" + c.ModelNameSuffix + " = kotlin.collections.List<kotlin.String>\n"
	if len(files) != 1 || files[path] != want {
		t.Fatal("graduated full array artifact mismatch", c.ID, files)
	}
}
