package testutil

import (
	"reflect"
	"strings"
	"testing"
)

// Retain the historical input/manifest bytes and graduate only this named case.
func NullableRawGraduation(c Case) bool { return c.ID == "nullable-component" }

func CheckNullableRawGraduation(t testing.TB, c Case, files map[string]string) {
	t.Helper()
	path := strings.ReplaceAll(c.PackageName+".models", ".", "/") + "/Record" + c.ModelNameSuffix + ".kt"
	content := "// Generated by openapi-kt. Do not edit.\npackage " + c.PackageName + ".models\n\npublic typealias Record" + c.ModelNameSuffix + " = kotlinx.serialization.json.JsonElement?\n"
	if !reflect.DeepEqual(files, map[string]string{path: content}) {
		t.Fatal("nullable raw graduation complete artifact mismatch", files)
	}
}
