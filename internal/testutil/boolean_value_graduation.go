package testutil

import (
	"fmt"
	"reflect"
	"strings"
	"testing"

	"openapi-kt/internal/diagnostic"
)

// BooleanValueGraduation changes only these historical cases' executable
// expectation; the original input, inventory and reviewed snapshots stay intact.
func BooleanValueGraduation(c Case) bool {
	return c.ID == "property-boolean" || c.ID == "component-boolean" || c.ID == "array-items-boolean"
}

func CheckBooleanValueGraduation(t testing.TB, c Case, files map[string]string, warnings []diagnostic.Diagnostic) {
	t.Helper()
	name := "Record" + c.ModelNameSuffix
	path := strings.ReplaceAll(c.PackageName+".models", ".", "/") + "/" + name + ".kt"
	if c.ID == "array-items-boolean" {
		qualified := c.PackageName + ".models." + name + ".FalseValue"
		expected := fmt.Sprintf(`// Generated by openapi-kt. Do not edit.
package %[3]s.models

@kotlinx.serialization.Serializable
public data class %[1]s(
    @kotlinx.serialization.SerialName("value")
    public val value: kotlin.collections.List<%[2]s>? = null,
) {
    @kotlinx.serialization.Serializable(with = %[2]s.Serializer::class)
    public sealed class FalseValue private constructor() {
        public object Serializer : kotlinx.serialization.KSerializer<%[2]s> {
            override val descriptor: kotlinx.serialization.descriptors.SerialDescriptor = kotlinx.serialization.descriptors.buildClassSerialDescriptor("%[2]s")
            override fun serialize(encoder: kotlinx.serialization.encoding.Encoder, value: %[2]s): kotlin.Unit =
                throw kotlinx.serialization.SerializationException("Schema false admits no JSON value.")
            override fun deserialize(decoder: kotlinx.serialization.encoding.Decoder): %[2]s =
                throw kotlinx.serialization.SerializationException("Schema false admits no JSON value.")
        }
    }
}
`, name, qualified, c.PackageName)
		if !reflect.DeepEqual(files, map[string]string{path: expected}) || len(warnings) != 0 {
			t.Fatal("original literalfalse array corpus artifact changed", files, warnings)
		}
		return
	}
	if c.ID == "component-boolean" {
		value := files[path]
		if len(files) != 1 || len(warnings) != 0 || !strings.Contains(value, "sealed class "+name+" private constructor()") || !strings.Contains(value, "override fun serialize(") || !strings.Contains(value, "override fun deserialize(") || strings.Count(value, "Schema false admits no JSON value.") != 2 {
			t.Fatal("original false-root corpus role did not retain uninhabited codec", files, warnings)
		}
		return
	}
	content := "// Generated by openapi-kt. Do not edit.\npackage " + c.PackageName + ".models\n\n@kotlinx.serialization.Serializable\npublic data class " + name + "(\n    @kotlinx.serialization.SerialName(\"value\")\n    public val value: kotlinx.serialization.json.JsonElement? = null,\n)\n"
	if !reflect.DeepEqual(files, map[string]string{path: content}) {
		t.Fatal("boolean value complete artifact mismatch", files)
	}
	if len(warnings) != 1 || warnings[0].Code != "W_BOOLEAN_SCHEMA_PROJECTION" || warnings[0].Pointer == nil || *warnings[0].Pointer != "/components/schemas/Record/properties/value" {
		t.Fatal("boolean value original warning mismatch", warnings)
	}
}
