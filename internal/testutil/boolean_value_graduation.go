package testutil

import (
	"reflect"
	"strings"
	"testing"

	"openapi-kt/internal/diagnostic"
)

// BooleanValueGraduation changes only this historical case's executable
// expectation; the original input, inventory and reviewed snapshots stay intact.
func BooleanValueGraduation(c Case) bool { return c.ID == "property-boolean" }

func CheckBooleanValueGraduation(t testing.TB, c Case, files map[string]string, warnings []diagnostic.Diagnostic) {
	t.Helper()
	name := "Record" + c.ModelNameSuffix
	path := strings.ReplaceAll(c.PackageName+".models", ".", "/") + "/" + name + ".kt"
	content := "// Generated by openapi-kt. Do not edit.\npackage " + c.PackageName + ".models\n\n@kotlinx.serialization.Serializable\npublic data class " + name + "(\n    @kotlinx.serialization.SerialName(\"value\")\n    public val value: kotlinx.serialization.json.JsonElement? = null,\n)\n"
	if !reflect.DeepEqual(files, map[string]string{path: content}) {
		t.Fatal("boolean value complete artifact mismatch", files)
	}
	if len(warnings) != 1 || warnings[0].Code != "W_BOOLEAN_SCHEMA_PROJECTION" || warnings[0].Pointer == nil || *warnings[0].Pointer != "/components/schemas/Record/properties/value" {
		t.Fatal("boolean value original warning mismatch", warnings)
	}
}
