package kotlin

import (
	"crypto/sha256"
	"fmt"
	"strings"

	"openapi-kt/internal/naming"
	"openapi-kt/internal/schema"
)

func EmitClient(client *schema.Client, rootPackage string) []File {
	if client == nil {
		return nil
	}
	apiPackage := rootPackage + ".api"
	var files []File
	errorHelper := clientNeedsErrorBody(client)
	if errorHelper {
		files = append(files, emitErrorBody(apiPackage))
	}
	files = append(files, emitServerDefaults(client.ServerDefaults, apiPackage)...)
	for _, group := range client.Groups {
		var out strings.Builder
		fmt.Fprintf(&out, "// Generated by openapi-kt. Do not edit.\npackage %s\n\n", apiPackage)
		out.WriteString("import io.ktor.client.call.body\nimport io.ktor.client.request.request\nimport io.ktor.client.request.parameter\nimport io.ktor.client.request.header\nimport io.ktor.client.request.setBody\nimport io.ktor.http.contentType\nimport io.ktor.http.encodeURLPathPart\n\n")
		if groupHasSSE(group) {
			out.WriteString("import io.ktor.client.plugins.sse.sse\nimport io.ktor.http.takeFrom\nimport kotlinx.coroutines.flow.collect\nimport kotlinx.serialization.decodeFromString\n\n")
		}
		if groupHasNullableIntResponse(group) {
			out.WriteString("import io.ktor.client.statement.bodyAsText\n")
			if !groupHasSSE(group) {
				out.WriteString("import kotlinx.serialization.decodeFromString\n")
			}
			out.WriteString("\n")
		}
		namespaces := planNamespaceImports(group)
		out.WriteString(namespaces.imports)
		baseType := "kotlin.String"
		if client.HasServerOverrides {
			baseType += "?"
		}
		fmt.Fprintf(&out, "public class %s(\n    private val client: io.ktor.client.HttpClient,\n    private val basePath: %s,\n", group.Name, baseType)
		if groupNeedsJSON(group) {
			out.WriteString("    private val json: kotlinx.serialization.json.Json = kotlinx.serialization.json.Json { ignoreUnknownKeys = true },\n")
		}
		out.WriteString(") {\n")
		for ordinal, op := range group.Operations {
			checks := planOperationInputChecks(op, ordinal+1)
			out.WriteString(checks.Declarations)
			emitOperationKdoc(op, errorHelper, &out)
			if op.SSE != nil {
				emitSSEOperation(group, op, checks, namespaces, &out)
				continue
			}
			fmt.Fprintf(&out, "    public suspend fun %s(\n", naming.CodeName(op.Name))
			for _, p := range op.Parameters {
				def := ""
				if !p.Required {
					def = " = null"
				}
				fmt.Fprintf(&out, "        %s: %s%s,\n", naming.CodeName(p.Name), RenderType(p.Type), def)
			}
			if op.Body != nil {
				def := ""
				if !op.Body.Required {
					def = " = null"
				}
				fmt.Fprintf(&out, "        input: %s%s,\n", RenderType(op.Body.Type), def)
			}
			out.WriteString("        requestBuilder: (io.ktor.client.request.HttpRequestBuilder.() -> kotlin.Unit)? = null,\n")
			fmt.Fprintf(&out, "    ): %s {\n", RenderType(op.Response))
			emitOperationInputChecks(op, checks, 2, &out)
			fmt.Fprintf(&out, "        return this@%s.client.request(%s) {\n", group.Name, urlExpression(group.Name, op))
			fmt.Fprintf(&out, "            this.method = %s(%s)\n", namespaces.httpMethodConstructor(op), naming.Literal(strings.ToUpper(op.Method)))
			if op.Body != nil {
				fmt.Fprintf(&out, "            contentType(%s.Application.Json)\n            setBody(input)\n", namespaces.contentTypeReference(op))
			}
			for _, p := range op.Parameters {
				if p.Location != "path" {
					emitRequestParameter(p, &out)
				}
			}
			out.WriteString("            requestBuilder?.invoke(this)\n")
			if nullableIntResponse(op) {
				fmt.Fprintf(&out, "        }.let { response -> this@%s.json.decodeFromString<%s>(response.bodyAsText()) }", group.Name, RenderType(op.Response))
			} else {
				fmt.Fprintf(&out, "        }.body<%s>()", RenderType(op.Response))
			}
			if typeHasValidation(op.Response) {
				out.WriteString(".also { result ->\n")
				emitTypeChecks(op.Response, "result", "Field value", 3, &out)
				out.WriteString("        }")
			}
			out.WriteString("\n    }\n\n")
		}
		out.WriteString("}\n")
		if groupHasUnique(group) {
			emitUniqueHelper(&out)
		}
		if groupHasJSONUnique(group) {
			emitJSONUniqueHelper(&out)
		}
		files = append(files, File{Path: strings.ReplaceAll(apiPackage, ".", "/") + "/" + group.Name + ".kt", Content: out.String()})
	}
	var out strings.Builder
	imports, constructors := planClientNamespaceImports(client, apiPackage)
	baseType, baseDefault := "kotlin.String", naming.Literal(client.BasePath)
	if client.HasServerOverrides {
		baseType, baseDefault = "kotlin.String?", "null"
	}
	fmt.Fprintf(&out, "// Generated by openapi-kt. Do not edit.\npackage %s\n\n%spublic class %s(\n    private val httpClient: io.ktor.client.HttpClient,\n    private val basePath: %s = %s,\n", rootPackage, imports, client.Name, baseType, baseDefault)
	if clientNeedsJSON(client) {
		out.WriteString("    private val json: kotlinx.serialization.json.Json = kotlinx.serialization.json.Json { ignoreUnknownKeys = true },\n")
	}
	out.WriteString(") {\n")
	for _, group := range client.Groups {
		args := "httpClient, basePath"
		if groupNeedsJSON(group) {
			args += ", json"
		}
		fmt.Fprintf(&out, "    public val %s: %s.%s by lazy { %s(%s) }\n", naming.CodeName(group.Property), apiPackage, group.Name, constructors[group.Name], args)
	}
	out.WriteString("}\n")
	files = append(files, File{Path: strings.ReplaceAll(rootPackage, ".", "/") + "/" + client.Name + ".kt", Content: out.String()})
	return files
}

func safeKdoc(text string) string {
	text = strings.ReplaceAll(text, "/*", "/ *")
	text = strings.ReplaceAll(text, "*/", "* /")
	text = strings.ReplaceAll(text, "\r", " ")
	text = strings.ReplaceAll(text, "\n", " ")
	return text
}

func serverDefaultName(identity string) string {
	return "`openapi-kt server " + identity + "`"
}

// Each immutable URL owns one content-addressed file. Equal defaults can share
// identical manifest bytes across named specs, independent of client names.
func emitServerDefaults(defaults []string, apiPackage string) []File {
	files := make([]File, 0, len(defaults))
	for _, base := range defaults {
		identity := fmt.Sprintf("%x", sha256.Sum256([]byte(base)))
		content := fmt.Sprintf("// Generated by openapi-kt. Do not edit.\npackage %s\n\ninternal object %s {\n    val basePath: kotlin.String = %s\n}\n", apiPackage, serverDefaultName(identity), naming.Literal(base))
		files = append(files, File{Path: strings.ReplaceAll(apiPackage, ".", "/") + "/ServerDefault_" + identity + ".kt", Content: content})
	}
	return files
}

func urlExpression(owner string, op schema.Operation) string {
	base := "this@" + owner + ".basePath"
	if op.ServerDefault != "" {
		base = "(" + base + " ?: " + serverDefaultName(op.ServerDefault) + ".basePath)"
	}
	parts := []string{base}
	rest := strings.TrimLeft(op.Path, "/")
	for rest != "" {
		start := strings.IndexByte(rest, '{')
		if start < 0 {
			parts = append(parts, naming.Literal(rest))
			break
		}
		if start > 0 {
			parts = append(parts, naming.Literal(rest[:start]))
		}
		end := start + 1 + strings.IndexByte(rest[start+1:], '}')
		wire := rest[start+1 : end]
		for _, p := range op.Parameters {
			if p.Location == "path" && p.Wire == wire {
				expr := naming.CodeName(p.Name)
				if p.Format == schema.CSVParameter {
					expr = joinedParameter(expr, p)
				} else if p.Enum || p.ValueClass {
					expr = wireParameter(expr, p)
					if p.ValueClass {
						expr += ".toString()"
					}
				} else if p.Type.Name != "kotlin.String" {
					expr += ".toString()"
				}
				parts = append(parts, expr+".encodeURLPathPart()")
				break
			}
		}
		rest = rest[end+1:]
	}
	return strings.Join(parts, " + ")
}
