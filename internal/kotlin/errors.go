package kotlin

import (
	"fmt"
	"strings"

	"openapi-kt/internal/schema"
)

func clientNeedsErrorBody(client *schema.Client) bool {
	for _, group := range client.Groups {
		for _, op := range group.Operations {
			for _, response := range op.Errors {
				if response.HasBody {
					return true
				}
			}
		}
	}
	return false
}

func emitErrorBody(pkg string) File {
	return File{Path: strings.ReplaceAll(pkg, ".", "/") + "/ErrorBody.kt", Content: "// Generated by openapi-kt. Do not edit.\npackage " + pkg + "\n\n" + errorBodySource}
}

func emitOperationKdoc(op schema.Operation, helper bool, out *strings.Builder) {
	if len(op.Errors) == 0 {
		if op.Summary != "" {
			fmt.Fprintf(out, "    /** %s */\n", safeKdoc(op.Summary))
		}
		return
	}
	out.WriteString("    /**\n")
	if op.Summary != "" {
		fmt.Fprintf(out, "     * %s\n     *\n", safeKdoc(op.Summary))
	}
	out.WriteString("     * Declared HTTP error responses")
	if helper {
		out.WriteString("; decode a ResponseException with [errorBody]")
	}
	out.WriteString(":\n")
	for _, response := range op.Errors {
		description := "no JSON body schema"
		if response.Type != nil {
			description = "[" + RenderType(*response.Type) + "]"
		} else if response.HasBody {
			description = "declared inline; no standalone error type"
		}
		fmt.Fprintf(out, "     * - `%s`: %s\n", response.Status, description)
	}
	out.WriteString("     */\n")
}

const errorBodySource = `import io.ktor.client.call.body

/**
 * Decode the still-readable error response as T, returning null on decoding failure.
 * The caller owns HTTP validation (for example, expectSuccess = true) and serializers.
 * Cancellation is propagated, never converted into a missing error body.
 */
public suspend inline fun <reified T> io.ktor.client.plugins.ResponseException.errorBody(): T? {
    try {
        return response.body<T>()
    } catch (cancelled: kotlin.coroutines.cancellation.CancellationException) {
        throw cancelled
    } catch (failure: kotlin.Exception) {
        return null
    }
}
`
