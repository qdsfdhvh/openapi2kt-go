package kotlin

import "strings"

// EmitPatch is independent of any one request shape. Presence is selected by
// the schema plan; the runtime itself is shared by all included request models.
func EmitPatch(pkg string) File {
	return File{Path: strings.ReplaceAll(pkg, ".", "/") + "/Patch.kt", Content: "// Generated by openapi-kt. Do not edit.\npackage " + pkg + "\n\n" + patchSource}
}

const patchSource = `@kotlinx.serialization.Serializable(with = PatchSerializer::class)
public sealed class Patch<out T> {
    public abstract val valueOrNull: T?

    public data object Absent : Patch<kotlin.Nothing>() {
        override val valueOrNull: kotlin.Nothing? get() = null
    }

    public data object Null : Patch<kotlin.Nothing>() {
        override val valueOrNull: kotlin.Nothing? get() = null
    }

    public data class Value<out T>(public val value: T) : Patch<T>() {
        override val valueOrNull: T get() = value
    }

    public companion object {
        public fun <T : kotlin.Any> ofNullable(value: T?): Patch<T> =
            if (value == null) Null else Value(value)

        public fun <T : kotlin.Any> orAbsent(value: T?): Patch<T> =
            if (value == null) Absent else Value(value)
    }
}

@kotlin.OptIn(kotlinx.serialization.ExperimentalSerializationApi::class)
public class PatchSerializer<T>(
    private val valueSerializer: kotlinx.serialization.KSerializer<T>,
) : kotlinx.serialization.KSerializer<Patch<T>> {
    override val descriptor: kotlinx.serialization.descriptors.SerialDescriptor = valueSerializer.descriptor

    override fun serialize(encoder: kotlinx.serialization.encoding.Encoder, value: Patch<T>) {
        when (value) {
            Patch.Absent -> throw kotlinx.serialization.SerializationException("Patch.Absent must be omitted by its containing property.")
            Patch.Null -> encoder.encodeNull()
            is Patch.Value -> encoder.encodeSerializableValue(valueSerializer, value.value)
        }
    }

    override fun deserialize(decoder: kotlinx.serialization.encoding.Decoder): Patch<T> {
        if (decoder.decodeNotNullMark()) return Patch.Value(decoder.decodeSerializableValue(valueSerializer))
        decoder.decodeNull()
        return Patch.Null
    }
}
`
