package kotlin

import "strings"

// EmitLongAsString is the field-only decimal-string utility. It intentionally
// delegates reading to decodeString/toLong rather than changing the caller's
// JSON decoder policy or globally retyping all Long values.
func EmitLongAsString(packageName string) File {
	content := `// Generated by openapi-kt. Do not edit.
package ` + packageName + `

internal object LongAsStringSerializer : kotlinx.serialization.KSerializer<kotlin.Long> {
    override val descriptor: kotlinx.serialization.descriptors.SerialDescriptor =
        kotlinx.serialization.descriptors.PrimitiveSerialDescriptor("LongAsStringSerializer", kotlinx.serialization.descriptors.PrimitiveKind.STRING)

    override fun serialize(encoder: kotlinx.serialization.encoding.Encoder, value: kotlin.Long) {
        encoder.encodeString(value.toString())
    }

    override fun deserialize(decoder: kotlinx.serialization.encoding.Decoder): kotlin.Long =
        decoder.decodeString().toLong()
}
`
	return File{Path: strings.ReplaceAll(packageName, ".", "/") + "/LongAsStringSerializer.kt", Content: content}
}
