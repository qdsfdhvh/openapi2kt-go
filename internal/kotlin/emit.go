// Package kotlin emits deterministic source from the private typed schema plan.
package kotlin

import (
	"fmt"
	"runtime"
	"strings"
	"sync"

	"openapi-kt/internal/naming"
	"openapi-kt/internal/schema"
)

type File struct{ Path, Content string }

func Emit(declarations []schema.Declaration, packageName string, hints schema.EmissionHints) []File {
	// Amortize scheduling on small plans and bound per-generation CPU/memory
	// pressure even when the host advertises many processors.
	workers := min(runtime.GOMAXPROCS(0), 8, max(1, len(declarations)/32))
	return emitFiles(declarations, packageName, hints, workers)
}

// Analysis and transformations must finish before emission. Declarations and
// hints are shared read-only; each worker owns its builder and result slots.
func emitFiles(declarations []schema.Declaration, packageName string, hints schema.EmissionHints, workers int) []File {
	pkg := packageName + ".models"
	directory := strings.ReplaceAll(pkg, ".", "/")
	files := make([]File, len(declarations))
	emit := func(worker int) {
		for i := worker; i < len(declarations); i += workers {
			files[i] = emitFile(declarations[i], pkg, directory, hints)
		}
	}
	if workers == 1 {
		emit(0)
	} else {
		var group sync.WaitGroup
		for worker := 1; worker < workers; worker++ {
			group.Go(func() { emit(worker) })
		}
		emit(0)
		group.Wait()
	}
	return files
}

func emitFile(declaration schema.Declaration, pkg, directory string, hints schema.EmissionHints) File {
	var out strings.Builder
	fmt.Fprintf(&out, "// Generated by openapi-kt. Do not edit.\npackage %s\n\n", pkg)
	if hasObjectUnion(declaration) {
		out.WriteString("import kotlinx.serialization.json.jsonObject\nimport kotlinx.serialization.json.jsonPrimitive\n\n")
	}
	if hasPrimitiveUnion(declaration) {
		out.WriteString("import kotlinx.serialization.json.booleanOrNull\nimport kotlinx.serialization.json.doubleOrNull\nimport kotlinx.serialization.json.longOrNull\n\n")
	}
	emitNullLiteralImports(declaration, &out)
	emitDeclaration(declaration, 0, pkg, hints, &out)
	emitDefaultHelpers(declaration, &out)
	emitArrayDefaultHelpers(declaration, &out)
	emitEnumDefaultHelpers(declaration, pkg, &out)
	emitObjectDefaultHelpers(declaration, pkg, &out)
	emitNullLiteralHelper(declaration, &out)
	emitStructuredConstHelpers(declaration, &out)
	if declarationHasUnique(declaration) {
		emitUniqueHelper(&out)
	}
	if declarationHasJSONUnique(declaration) {
		emitJSONUniqueHelper(&out)
	}
	return File{Path: directory + "/" + declaration.Name() + ".kt", Content: out.String()}
}

func emitDeclaration(declaration schema.Declaration, indent int, owner string, hints schema.EmissionHints, out *strings.Builder) {
	switch d := declaration.(type) {
	case *schema.PrimitiveValueClass:
		emitValueClass(d, out)
	case *schema.ScalarAlias:
		fmt.Fprintf(out, "public typealias %s = %s\n", d.ClassName, d.Scalar)
		if d.ComponentDefault != "" {
			// A typealias cannot own members, so the factory is a top-level
			// function with the same opt-in contract.
			helper := "`openapi-kt component default " + strings.ReplaceAll(owner+"."+d.ClassName, ".", " ") + "`"
			fmt.Fprintf(out, "\n// The OpenAPI component default for this schema.\npublic fun `%s default`(): %s = %s(%s)\n",
				d.ClassName, d.ClassName, helper, naming.Literal(d.ComponentDefault))
			fmt.Fprintf(out, "\nprivate fun %s(source: kotlin.String): %s = kotlinx.serialization.json.Json.decodeFromString(kotlinx.serialization.serializer<%s>(), source)\n",
				helper, d.ClassName, d.ClassName)
		}
	case *schema.ValueAlias:
		fmt.Fprintf(out, "public typealias %s = %s\n", d.ClassName, RenderType(d.Type))
		if d.ComponentDefault != "" {
			// A typealias cannot own members, so the factory is top-level.
			fmt.Fprintf(out, "\n// The OpenAPI component default for this schema.\npublic fun `%s default`(): %s = `openapi-kt component default %s`(%s)\n",
				d.ClassName, d.ClassName, strings.ReplaceAll(owner+"."+d.ClassName, ".", " "), naming.Literal(d.ComponentDefault))
		}
	case *schema.Model:
		if len(d.Properties) == 0 && len(d.Constants) == 0 {
			raw := schema.TypeRef{Kind: schema.JSON}
			if d.Nullable {
				raw = raw.Null()
			}
			fmt.Fprintf(out, "public typealias %s = %s\n", d.ClassName, RenderType(raw))
		} else {
			emitModel(d, indent, owner, hints, out)
		}
	case *schema.StringEnum:
		emitStringEnum(d, indent, owner, out)
	case *schema.PrimitiveUnion:
		emitPrimitiveUnion(d, indent, owner, hints, out)
	case *schema.ObjectUnion:
		emitObjectUnion(d, indent, owner, hints, out)
	case *schema.Hierarchy:
		emitHierarchy(d, owner, hints, out)
	case *schema.SSEEvents:
		emitSSEEvents(d, out)
	default:
		panic("unhandled Kotlin declaration plan") // internal IR bug, never input dispatch
	}
}

// Backing peers are declared in the alias's package, not the consuming API
// package. Qualify a copied render view; never mutate the shared forward plan.
func qualifyAliasView(t schema.TypeRef, pkg string) schema.TypeRef {
	if t.Kind == schema.Named && !strings.Contains(t.Name, ".") {
		t.Name = pkg + "." + t.Name
	}
	if t.Element != nil {
		element := qualifyAliasView(*t.Element, pkg)
		t.Element = &element
	}
	return t
}

func RenderType(t schema.TypeRef) string {
	if t.ArrayAliasView == schema.NonNullArrayAlias {
		target := t.Element.WithoutRootNull()
		pkg := t.Name[:strings.LastIndex(t.Name, ".")]
		target = qualifyAliasView(target, pkg)
		target.Serializer = t.Serializer
		return RenderType(target)
	}
	if t.Serializer != "" {
		serializer := t.Serializer
		t.Serializer = ""
		return "@kotlinx.serialization.Serializable(with = " + serializer + "::class) " + RenderType(t)
	}
	switch t.Kind {
	case schema.Scalar, schema.Named, schema.InlineValue:
		return t.Name
	case schema.List:
		return "kotlin.collections.List<" + RenderType(*t.Element) + ">"
	case schema.Nullable:
		return RenderType(*t.Element) + "?"
	case schema.JSON:
		return "kotlinx.serialization.json.JsonElement"
	case schema.Map:
		return "kotlin.collections.Map<kotlin.String, " + RenderType(*t.Element) + ">"
	case schema.JSONObject:
		return "kotlinx.serialization.json.JsonObject"
	case schema.PatchValue:
		return t.Name + "<" + RenderType(*t.Element) + ">"
	default:
		panic("unhandled Kotlin type plan")
	}
}

func emitModel(model *schema.Model, indent int, owner string, hints schema.EmissionHints, out *strings.Builder) {
	emitModelWithSuper(model, indent, owner, "", hints, out)
}

func emitModelWithSuper(model *schema.Model, indent int, owner, superType string, hints schema.EmissionHints, out *strings.Builder) {
	emitModelContext(model, indent, owner, superType, nil, nil, false, hints, out)
}

func emitModelContext(model *schema.Model, indent int, owner, superType string, common []schema.Property, serialName *string, nonNullSingleton bool, hints schema.EmissionHints, out *strings.Builder) {
	pad := strings.Repeat("    ", indent)
	superclass := ""
	if superType != "" {
		superclass = " : " + superType + "()"
	}
	if len(model.Constants) != 0 || schema.ModelHasPatch(model) || model.PropertyCount != nil {
		fmt.Fprintf(out, "%s@kotlin.OptIn(kotlinx.serialization.ExperimentalSerializationApi::class)\n", pad)
	}
	singleton := common != nil && len(model.Properties) == 0
	override := func(wire string) string {
		for _, p := range common {
			if p.WireName == wire {
				return "override "
			}
		}
		return ""
	}
	if model.PropertyCount != nil {
		fmt.Fprintf(out, "%s@kotlinx.serialization.KeepGeneratedSerializer\n", pad)
		fmt.Fprintf(out, "%s@kotlinx.serialization.Serializable(with = %s.%s.%s::class)\n", pad, owner, model.ClassName, propertyCountSerializerName(model))
	} else if singleton && len(model.Constants) > 0 {
		fmt.Fprintf(out, "%s@kotlinx.serialization.Serializable(with = %s.%s.Serializer::class)\n", pad, owner, model.ClassName)
	} else {
		fmt.Fprintf(out, "%s@kotlinx.serialization.Serializable\n", pad)
	}
	if serialName != nil {
		fmt.Fprintf(out, "%s@kotlinx.serialization.SerialName(%s)\n", pad, naming.Literal(*serialName))
	}
	if singleton {
		fmt.Fprintf(out, "%spublic data object %s%s {\n", pad, model.ClassName, superclass)
	} else if len(model.Properties) == 0 {
		fmt.Fprintf(out, "%spublic class %s%s {\n", pad, model.ClassName, superclass)
	} else {
		fmt.Fprintf(out, "%spublic %s %s(\n", pad, classKeyword(model.Plain), model.ClassName)
	}
	for _, p := range model.Properties {
		fmt.Fprintf(out, "%s    @kotlinx.serialization.SerialName(%s)\n", pad, naming.Literal(p.WireName))
		defaultNull := ""
		if p.DefaultNull {
			defaultNull = " = null"
		}
		if p.Default != "" {
			defaultNull = " = " + defaultExpression(model, p, owner)
		}
		if p.Type.Kind == schema.PatchValue {
			fmt.Fprintf(out, "%s    @kotlinx.serialization.EncodeDefault(kotlinx.serialization.EncodeDefault.Mode.NEVER)\n", pad)
			defaultNull = " = " + p.Type.Name + ".Absent"
		}
		fmt.Fprintf(out, "%s    public %sval %s: %s%s,\n", pad, override(p.WireName), p.Name, RenderType(p.Type), defaultNull)
	}
	// A component-level default never becomes an initializer. The class keeps its
	// constructor and presence classification; the factory below is opt-in.
	if !model.Plain && len(model.Properties) != 0 && len(model.Nested) == 0 && len(model.Constants) == 0 && !modelHasValidation(model) && model.PropertyCount == nil && model.ComponentDefault == "" {
		fmt.Fprintf(out, "%s)%s\n", pad, superclass)
		return
	}
	if len(model.Properties) != 0 {
		fmt.Fprintf(out, "%s)%s {\n", pad, superclass)
	}
	emitModelValidation(model, indent+1, hints, out)
	if model.Plain {
		reserved := []string{}
		for _, c := range model.Constants {
			reserved = append(reserved, c.Name)
		}
		for _, d := range model.Nested {
			reserved = append(reserved, d.Name())
		}
		for _, p := range common {
			reserved = append(reserved, p.Name)
		}
		emitPlainMembers(model.ClassName, model.Properties, reserved, indent+1, out)
	}
	for i, c := range model.Constants {
		if i > 0 {
			out.WriteByte('\n')
		}
		fmt.Fprintf(out, nullLiteralTemplate("%s    @kotlinx.serialization.EncodeDefault(kotlinx.serialization.EncodeDefault.Mode.ALWAYS)\n", modelNeedsNullLiteralAliases(model)), pad)
		fmt.Fprintf(out, nullLiteralTemplate("%s    @kotlinx.serialization.SerialName(%s)\n", modelNeedsNullLiteralAliases(model)), pad, naming.Literal(c.WireName))
		fmt.Fprintf(out, "%s    public %sval %s: %s = %s\n", pad, override(c.WireName), c.Name, RenderType(c.Type), nullConstantExpression(c))
	}
	if singleton && len(model.Constants) > 0 {
		emitSingletonSerializer(model, indent+1, owner, nonNullSingleton, out)
	}
	if model.PropertyCount != nil {
		emitPropertyCountSerializer(model, indent+1, owner, out)
	}
	if model.ComponentDefault != "" {
		emitComponentDefaultFactory(model, indent+1, owner, out)
	}
	for i, nested := range model.Nested {
		if i > 0 || len(model.Constants) != 0 {
			out.WriteByte('\n')
		}
		emitDeclaration(nested, indent+1, owner+"."+model.ClassName, hints, out)
	}
	fmt.Fprintf(out, "%s}\n", pad)
}

func emitStringEnum(model *schema.StringEnum, indent int, owner string, out *strings.Builder) {
	pad, name := strings.Repeat("    ", indent), model.ClassName
	qualified := owner + "." + name
	ty := name
	for _, member := range model.Members {
		if member.Name == name {
			ty = qualified
		}
	}
	lines := []string{
		"@kotlinx.serialization.Serializable(with = " + ty + ".Serializer::class)",
		"public sealed class " + name + " {",
		"    public abstract val serialName: kotlin.String",
	}
	for _, member := range model.Members {
		lines = append(lines, "", "    public data object "+member.Name+" : "+ty+"() {",
			"        override val serialName: kotlin.String = "+naming.Literal(member.Wire), "    }")
	}
	members := make([]string, 0, len(model.Members))
	for _, member := range model.Members {
		members = append(members, member.Name)
	}
	lines = append(lines, "")
	if model.Plain {
		lines = append(lines, "    public class Unrecognized(override val serialName: kotlin.String) : "+ty+"() {")
		var members strings.Builder
		emitPlainMembers("Unrecognized", []schema.Property{{Name: "serialName"}}, nil, 2, &members)
		lines = append(lines, strings.Split(strings.TrimSuffix(members.String(), "\n"), "\n")...)
		lines = append(lines, "    }")
	} else {
		lines = append(lines, "    public data class Unrecognized(override val serialName: kotlin.String) : "+ty+"()")
	}
	lines = append(lines,
		"", "    public companion object {",
		"        public val entries: kotlin.collections.List<"+ty+"> by kotlin.lazy {",
		"            kotlin.collections.listOf("+strings.Join(members, ", ")+")", "        }",
		"", "        public fun fromSerialName(value: kotlin.String): "+ty+" = Serializer.fromSerialName(value)",
	)
	lines = append(lines,
		"    }", "", "    public object Serializer : kotlinx.serialization.KSerializer<"+ty+"> {",
		"        override val descriptor: kotlinx.serialization.descriptors.SerialDescriptor =",
		"            kotlinx.serialization.descriptors.PrimitiveSerialDescriptor("+naming.Literal(qualified)+", kotlinx.serialization.descriptors.PrimitiveKind.STRING)",
		"", "        override fun serialize(encoder: kotlinx.serialization.encoding.Encoder, value: "+ty+") {",
		"            encoder.encodeString(value.serialName)", "        }",
		"", "        override fun deserialize(decoder: kotlinx.serialization.encoding.Decoder): "+ty+" {",
		"            val value = if (decoder is kotlinx.serialization.json.JsonDecoder) {",
		"                val element = decoder.decodeJsonElement()",
		"                if (element !is kotlinx.serialization.json.JsonPrimitive || !element.isString) {",
		"                    throw kotlinx.serialization.SerializationException(\"Expected a JSON string for an enum.\")",
		"                }", "                element.content", "            } else {",
		"                decoder.decodeString()", "            }", "            return fromSerialName(value)", "        }",
		"", "        public fun fromSerialName(value: kotlin.String): "+ty+" = when (value) {",
	)
	for _, member := range model.Members {
		lines = append(lines, "            "+naming.Literal(member.Wire)+" -> "+member.Name)
	}
	lines = append(lines, "            else -> Unrecognized(value)", "        }", "    }", "}")
	for _, line := range lines {
		if line == "" {
			out.WriteByte('\n')
		} else {
			fmt.Fprintf(out, "%s%s\n", pad, line)
		}
	}
}
